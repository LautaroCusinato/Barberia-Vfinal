import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const read = (relative) => fs.readFileSync(path.join(root, relative), 'utf8')
const api = read('supabase/functions/billing-api/index.ts')
const hooks = read('supabase/functions/billing-webhooks/index.ts')
const jobs = read('supabase/functions/billing-jobs/index.ts')
const providers = read('supabase/functions/_shared/providers.ts')
const supabaseShared = read('supabase/functions/_shared/supabase.ts')
const sharedHttp = read('supabase/functions/_shared/http.ts')
const platformPage = read('src/pages/PlatformCRM.jsx')
const sandboxAudit = read('supabase/migrations/20260807100000_billing_sandbox_audit.sql')

for (const route of ['checkout', 'status', 'config-status', 'external-status', 'sync-plans', 'reconcile']) assert.match(api, new RegExp(`route === '${route}'`), `falta ruta ${route}`)
for (const name of ['verifyMercadoPago', 'verifyPayPal', 'mercadoPagoResource', 'paypalResource', 'mercadoPagoExternalStatus', 'paypalExternalStatus']) assert.match(hooks + providers, new RegExp(name), `falta ${name}`)
for (const secret of ['MERCADOPAGO_ACCESS_TOKEN', 'MERCADOPAGO_WEBHOOK_SECRET', 'PAYPAL_CLIENT_ID', 'PAYPAL_CLIENT_SECRET', 'PAYPAL_WEBHOOK_ID', 'SUPABASE_SERVICE_ROLE_KEY', 'APP_BASE_URL']) assert.match(api + hooks + jobs + providers + supabaseShared, new RegExp(secret))
assert.match(api, /checkoutTenant\(admin, userId, body\)/)
assert.match(api, /metadata\.environment !== 'sandbox'/)
assert.match(api, /metadata\.technical !== true/)
assert.match(api, /sandbox_scope_required/)
assert.match(api, /billing_plan === planCode/)
assert.doesNotMatch(api, /sandbox_enabled_at/)
assert.match(api, /p_plan_codigo: planCode/)
assert.doesNotMatch(api + hooks + jobs + providers + supabaseShared, /(sk_live_|sk_test_|service_role_key\s*=\s*['"][^$])/i)
assert.match(hooks, /p_signature_valid: true/)
assert.match(hooks, /transition_saas_subscription/)
assert.match(hooks, /amount_or_currency_mismatch/)
assert.match(providers, /MERCADOPAGO_ENVIRONMENT/)
assert.match(providers, /TEST-/)
assert.match(providers, /X-Idempotency-Key/)
assert.match(providers, /back_url/, 'Mercado Pago plan sync debe enviar back_url')
assert.match(api, /mp-checkout:/)
assert.match(api, /mp-plan:/)
assert.match(hooks, /externalReference/)
assert.match(hooks, /resourceType === 'payment'/)
assert.match(api, /subscription_registration_failed/)
assert.match(api, /provider === 'mercadopago' \? 'checkout'/)
assert.match(api, /sandbox_token_valid/)
assert.match(api, /corsHeaders/, 'billing-api debe responder preflight CORS')
assert.match(sharedHttp, /Access-Control-Allow-Headers/, 'el contrato CORS debe permitir Authorization')
assert.match(api, /Para sincronizar se debe indicar un único plan válido/)
assert.match(api, /eq\('codigo', planCode\)/)
assert.match(api, /const tenantId = await checkoutTenant\(admin, userId, body\)/, 'external-status debe aceptar el tenant sandbox validado')
for (const contract of ['SANDBOX_BILLING', 'tenantId: 6', "planCode: 'starter'", "provider: 'mercadopago'", "environment: 'sandbox'", 'config-status', 'sync-plans', 'external-status', 'record_billing_sandbox_audit', 'Confirmar sincronización', 'Token TEST- válido']) assert.match(platformPage, new RegExp(contract.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')), `falta control sandbox ${contract}`)
assert.match(platformPage, /!\['owner', 'admin'\]\.includes\(role\)/, 'el control sandbox debe estar restringido a owner/admin')
assert.doesNotMatch(platformPage, /PAYPAL|paypal/, 'el control sandbox no debe exponer PayPal')
assert.doesNotMatch(platformPage, /access_token[^\n]*console|console\.(log|info|debug)[^\n]*session/i, 'no debe imprimir secretos ni sesión')
for (const contract of ['record_billing_sandbox_audit', "role in ('owner', 'admin')", "barberia_id, metadata", 'tenant_id', 'environment', 'checkout_attempt_id']) assert.match(sandboxAudit, new RegExp(contract.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')), `falta auditoría sandbox ${contract}`)
assert.match(jobs, /BILLING_CRON_SECRET/)
assert.match(jobs, /BILLING_OUTBOX_SINK_URL/)
assert.match(jobs, /scheduled_reconciliation/)
console.log('Serverless billing verification passed: API autenticada, webhooks firmados, reconciliación y cron seguros.')
